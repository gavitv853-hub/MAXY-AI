class WebsiteGenerator(private val context: Context) {

    fun generateWebsiteFromPrompt(prompt: String): WebProject {
        val lower = prompt.lowercase()
        return when {
            lower.contains("gaming") || lower.contains("tournament") -> {
                generateGamingSite(prompt)
            }
            lower.contains("portfolio") || lower.contains("resume") -> {
                generatePortfolioSite(prompt)
            }
            lower.contains("restaurant") || lower.contains("food") || lower.contains("cafe") -> {
                generateRestaurantSite(prompt)
            }
            else -> {
                generateModernLandingPage(prompt)
            }
        }
    }

    fun exportToZip(project: WebProject): File? {
        return try {
            val exportDir = File(context.cacheDir, "exports")
            if (!exportDir.exists()) exportDir.mkdirs()

            val sanitizedTitle = project.title.replace(Regex("[^a-zA-Z0-9]"), "_").lowercase()
            val zipFile = File(exportDir, "${sanitizedTitle}_website.zip")
            if (zipFile.exists()) zipFile.delete()

            ZipOutputStream(FileOutputStream(zipFile)).use { zos ->
                // 1. index.html
                zos.putNextEntry(ZipEntry("index.html"))
                zos.write(project.htmlContent.toByteArray())
                zos.closeEntry()

                // 2. style.css
                zos.putNextEntry(ZipEntry("style.css"))
                zos.write(project.cssContent.toByteArray())
                zos.closeEntry()

                // 3. script.js
                zos.putNextEntry(ZipEntry("script.js"))
                zos.write(project.jsContent.toByteArray())
                zos.closeEntry()

                // 4. README.md
                val readme = """
# ${project.title}
Generated by **MAXY AI — JARVIS Personal Assistant**.

## Prompt:
> ${project.prompt}

## How to Run:
1. Extract all files to a folder.
2. Double-click `index.html` to open in any web browser.
3. Deploy for free to GitHub Pages, Netlify, or Vercel.
                """.trimIndent()
                zos.putNextEntry(ZipEntry("README.md"))
                zos.write(readme.toByteArray())
                zos.closeEntry()
            }
            zipFile
        } catch (e: Exception) {
            null
        }
    }

    fun shareZipFile(zipFile: File) {
        try {
            val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", zipFile)
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "application/zip"
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, "Website Export: ${zipFile.name}")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            context.startActivity(Intent.createChooser(intent, "Export Website Project").apply {
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            })
        } catch (_: Exception) {
            // Fallback for sharing without fileprovider if needed
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "application/zip"
                putExtra(Intent.EXTRA_TEXT, "MAXY AI Website Project created at: ${zipFile.absolutePath}")
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            context.startActivity(Intent.createChooser(intent, "Share Website").apply {
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            })
        }
    }

    fun buildPreviewHtml(project: WebProject): String {
        // Embed css and js inline for smooth Android WebView rendering
        val cssTag = "<style>\n${project.cssContent}\n</style>"
        val jsTag = "<script>\n${project.jsContent}\n</script>"

        var combined = project.htmlContent
        combined = if (combined.contains("</head>")) {
            combined.replace("</head>", "$cssTag\n</head>")
        } else {
            "$cssTag\n$combined"
        }

        combined = if (combined.contains("</body>")) {
            combined.replace("</body>", "$jsTag\n</body>")
        } else {
            "$combined\n$jsTag"
        }
        return combined
    }

